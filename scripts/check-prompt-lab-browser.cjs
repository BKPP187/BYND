'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.BYND_PLAYWRIGHT || 'C:/Users/l/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'artifacts/prompt-lab');
fs.mkdirSync(output, { recursive: true });
(async () => {
    const browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 375, height: 844 }, deviceScaleFactor: 2 });
    const errors = [], requests = [];
    let mode = 'normal';
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://eval.invalid/**', async route => {
        const body = route.request().postDataJSON(); requests.push(body);
        if (mode === 'http') { await route.fulfill({ status: 429, contentType: 'application/json', body: JSON.stringify({ error: { message: 'mock rate limit' } }) }); return; }
        const system = body.messages[0]?.content || '';
        let content;
        if (system.includes('独立评审')) {
            const sample = JSON.parse(body.messages[1].content);
            content = mode === 'judge' ? '{"pass":"yes"}' : JSON.stringify({ pass: sample.output === 'good', reason: sample.output === 'good' ? '符合角色' : '偏离角色', evidence: sample.output === 'good' ? '' : 'wrong' });
        } else if (system.includes('BYND Prompt 优化器')) {
            const sample = JSON.parse(body.messages[1].content);
            assert.ok(sample.failures.every(row => row.input.startsWith('dev')), 'optimizer only sees development cases');
            content = JSON.stringify({ scope: sample.scope, text: '保持角色', hypothesis: '明确行为以避免 OOC' });
        } else content = body.messages.some(m => m.content.includes('Prompt Lab 行为补充')) ? 'good' : 'wrong';
        await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { content }, finish_reason: 'stop' }], usage: { prompt_tokens: 100, completion_tokens: 10, total_tokens: 110 } }) });
    });
    try {
        await page.goto(pathToFileURL(path.join(root, 'index.html')).href, { waitUntil: 'domcontentloaded', timeout: 60000 });
        await page.waitForFunction(() => !!window.ByndPromptLab && typeof openSettingsTab === 'function');
        await page.evaluate(async () => { await byndStylesReady; unlockPhone(); document.documentElement.classList.add('mobile-runtime'); openApp('settings'); ByndBuiltinLibrary?.close(); openSettingsTab('lab'); });
        await page.locator('#lab-experiment').waitFor();
        assert.equal(await page.locator('#bynd-prompt-lab select:visible').count(), 1, 'only the experiment model is visible by default');
        assert.equal(await page.locator('#bynd-prompt-lab textarea:visible').count(), 0, 'internal prompt editors are hidden');
        assert.equal(await page.locator('#lab-model-config').getAttribute('open'), null);
        await page.locator('#lab-model-config > summary').click();
        assert.equal(await page.locator('#lab-model-config select:visible').count(), 3, 'advanced configuration exposes all three roles');
        assert.equal(await page.locator('#lab-judge').inputValue(), 'follow-experiment');
        assert.equal(await page.locator('#lab-proposer').inputValue(), 'follow-experiment');
        await page.screenshot({ path: path.join(output, 'lab-advanced-models-375.png'), animations: 'disabled' });
        await page.locator('#lab-model-config > summary').click();
        await page.locator('#lab-options > summary').click();
        await page.selectOption('#lab-policy', 'custom');
        await page.locator('#lab-custom-policy > summary').click();
        for (const label of await page.locator('#lab-custom-policy .lab-editor > label').allTextContents()) assert.doesNotMatch(label, /persona|knowledge|tools|initiative|context|decision|reality/);
        for (const input of await page.locator('[data-lab-module]').all()) assert.ok((await input.inputValue()).trim(), 'manual editor starts with built-in strategy rather than blank fields');
        await page.screenshot({ path: path.join(output, 'lab-custom-policy-375.png'), animations: 'disabled' });
        await page.selectOption('#lab-policy', 'builtin');
        await page.locator('#lab-options > summary').click();
        for (const width of [320, 375, 430]) {
            await page.setViewportSize({ width, height: 844 });
            const bounds = await page.evaluate(() => {
                const root = document.getElementById('bynd-prompt-lab').getBoundingClientRect();
                const header = document.querySelector('#app-settings-window .window-header h3').getBoundingClientRect();
                return { width: innerWidth, left: root.left, right: root.right, headerTop: header.top, overflow: document.documentElement.scrollWidth > innerWidth };
            });
            assert.ok(bounds.left >= 0 && bounds.right <= bounds.width + 1, 'lab fits narrow screen');
            assert.equal(bounds.overflow, false, 'page does not overflow horizontally');
            assert.ok(bounds.headerTop >= 10, 'settings heading remains inside the visible header');
            await page.screenshot({ path: path.join(output, `lab-${width}.png`), animations: 'disabled' });
        }
        for (const width of [320, 375, 430]) for (const inset of [47, 59]) for (const owner of ['parent', 'header']) {
            await page.setViewportSize({ width, height: 844 });
            const bounds = await page.evaluate(({ inset, owner }) => {
                const phone = document.querySelector('.phone-container');
                document.body.style.paddingTop = owner === 'parent' ? inset + 'px' : '0px';
                phone.style.height = owner === 'parent' ? `calc(100dvh - ${inset}px)` : '100dvh';
                phone.style.setProperty('--bynd-header-safe-top', owner === 'header' ? inset + 'px' : '0px');
                const header = document.querySelector('#app-settings-window .window-header');
                const title = header.querySelector('h3').getBoundingClientRect();
                const close = header.querySelector('.close-btn').getBoundingClientRect();
                return { titleTop: title.top, closeTop: close.top, height: header.getBoundingClientRect().height, overflow: document.documentElement.scrollWidth > innerWidth };
            }, { inset, owner });
            assert.ok(bounds.titleTop >= inset && bounds.closeTop >= inset, `header controls clear ${inset}px inset owned by ${owner}`);
            assert.ok(Math.abs(bounds.height - 52 - (owner === 'header' ? inset : 0)) < 1, 'inset reserved exactly once');
            assert.equal(bounds.overflow, false);
            if (width === 375) await page.screenshot({ path: path.join(output, `lab-safe-${owner}-${inset}-375.png`), animations: 'disabled' });
        }
        await page.setViewportSize({ width: 375, height: 844 });
        await page.evaluate(() => { document.body.style.paddingTop = ''; const phone = document.querySelector('.phone-container'); phone.style.height = ''; phone.style.removeProperty('--bynd-header-safe-top'); });
        const failedSave = await page.evaluate(() => {
            const original = Storage.prototype.setItem;
            Storage.prototype.setItem = function (key, value) { if (key === ByndPromptStore.KEY) throw new Error('模拟磁盘满'); return original.call(this, key, value); };
            try { ByndPromptLab.action('seed'); return document.getElementById('prompt-lab-status').textContent; } finally { Storage.prototype.setItem = original; }
        });
        assert.match(failedSave, /操作失败.*模拟磁盘满/);
        assert.equal(await page.locator('#lab-json').count(), 0, 'paste box is removed');
        const chooserEvent = page.waitForEvent('filechooser');
        await page.locator('[data-lab="import"]').click();
        const chooser = await chooserEvent;
        const beforeImport = await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY));
        await chooser.setFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{bad') });
        await page.waitForFunction(() => document.getElementById('prompt-lab-status').textContent.startsWith('导入失败：'));
        assert.equal(await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY)), beforeImport);
        const validBackup = await page.evaluate(() => ByndPromptLab.store.exportData({ draftMode: 'builtin', modelPreferences: { experiment: '', judge: 'follow-experiment', proposer: 'follow-experiment' }, config: { rounds: 4, repeats: 3, maxCalls: 500, maxMinutes: 25 } }));
        await page.evaluate(() => { window.labOriginalFileText = File.prototype.text; File.prototype.text = async () => { throw new Error('读取不可用'); }; });
        await page.locator('#lab-backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(validBackup) });
        await page.waitForFunction(() => document.getElementById('prompt-lab-status').textContent.includes('导入失败：读取不可用'));
        await page.evaluate(() => { File.prototype.text = window.labOriginalFileText; delete window.labOriginalFileText; });
        assert.equal(await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY)), beforeImport);
        await page.evaluate(() => { window.labOriginalStorageWrite = Storage.prototype.setItem; Storage.prototype.setItem = function (key, value) { if (key === ByndPromptStore.KEY) throw new Error('模拟磁盘满'); return window.labOriginalStorageWrite.call(this, key, value); }; });
        await page.locator('#lab-backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(validBackup) });
        await page.waitForFunction(() => document.getElementById('prompt-lab-status').textContent.includes('导入失败：模拟磁盘满'));
        await page.evaluate(() => { Storage.prototype.setItem = window.labOriginalStorageWrite; delete window.labOriginalStorageWrite; });
        assert.equal(await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY)), beforeImport);
        await page.locator('#lab-backup-file').setInputFiles({ name: 'large.json', mimeType: 'application/json', buffer: Buffer.alloc(10000001, 32) });
        await page.waitForFunction(() => document.getElementById('prompt-lab-status').textContent.includes('导入失败：导入文件超过 10 MB'));
        assert.equal(await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY)), beforeImport);
        await page.locator('#lab-backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(validBackup) });
        await page.waitForFunction(() => document.getElementById('prompt-lab-status').textContent.includes('实验数据已导入'));
        assert.equal(await page.locator('#lab-rounds').inputValue(), '4');
        assert.equal(await page.locator('#lab-repeats').inputValue(), '3');
        assert.equal(await page.locator('#lab-calls').inputValue(), '500');
        assert.equal(await page.locator('#lab-minutes').inputValue(), '25');
        assert.equal(await page.locator('#lab-backup-file').inputValue(), '', 'same file can be selected again');
        await page.locator('.lab-data').scrollIntoViewIfNeeded();
        await page.screenshot({ path: path.join(output, 'lab-backup-375.png'), animations: 'disabled' });
        const savedImport = await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY));
        await page.locator('#lab-backup-file').setInputFiles([]);
        assert.equal(await page.evaluate(() => localStorage.getItem(ByndPromptStore.KEY)), savedImport, 'cancel does not change saved data');
        const downloadEvent = page.waitForEvent('download');
        await page.locator('[data-lab="export"]').click();
        const download = await downloadEvent;
        assert.equal(download.suggestedFilename(), 'BYND-prompt-lab.json');
        assert.equal(await download.failure(), null);
        const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
        assert.equal(exported.experimentSettings.config.rounds, 4);
        assert.equal(exported.experimentSettings.draftMode, 'builtin');
        assert.ok(Array.isArray(exported.cases) && exported.cases.length);
        const failedExport = await page.evaluate(() => { const original = URL.createObjectURL; URL.createObjectURL = () => { throw new Error('下载不可用'); }; try { ByndPromptLab.action('export'); return document.getElementById('prompt-lab-status').textContent; } finally { URL.createObjectURL = original; } });
        assert.match(failedExport, /操作失败.*下载不可用/);
        await page.evaluate(() => { ByndPromptLab.store.saveDraft({ modules: { persona: '保留已有角色策略' } }); ByndPromptLab.render(); });
        assert.equal(await page.locator('#lab-policy').inputValue(), 'custom');
        assert.equal(await page.locator('[data-lab-module="persona"]').inputValue(), '保留已有角色策略', 'existing custom draft is preserved');
        await page.evaluate(() => {
            saveApiData({ apis: ['target', 'other', 'judge', 'proposer'].map(role => ({ id: 'mock-' + role, name: '测试 ' + role, baseUrl: 'https://eval.invalid/v1', model: 'mock-' + role, apiKey: 'test-secret' })), defaultId: 'mock-target' });
            const cases = ['dev', 'validation', 'test'].flatMap(split => [0, 1, 2].map(index => ({ id: split + index, split, category: 'ooc', lane: 'chat', character: { id: 'mock-lin', name: '林间', description: '沉稳的图书管理员' }, input: split + '角色场景' + index, rubric: '保持角色', events: [], memories: [], worldBook: [] })));
            ByndPromptLab.store.update(data => { data.cases = cases; data.draft = ByndPromptEval.BASELINE; data.draftMode = 'builtin'; data.report = null; });
            ByndPromptLab.render(); document.getElementById('lab-rounds').value = '1';
        });
        const builtinStart = requests.length;
        await page.evaluate(() => ByndPromptLab.start());
        assert.equal(await page.evaluate(() => ByndPromptLab.store.read().report.status), 'complete');
        assert.equal(await page.evaluate(() => ByndPromptEval.fingerprint(ByndPromptLab.store.read().report.initial) === ByndPromptEval.fingerprint(ByndPromptEval.SEED)), true, 'default run uses built-in policy without saving a draft');
        assert.ok(requests.slice(builtinStart).every(body => body.model === 'mock-target'), 'default target and judge use the current chat model');
        await page.evaluate(() => { ByndPromptLab.store.saveDraft(ByndPromptEval.BASELINE); ByndPromptLab.store.update(data => { data.report = null; }); ByndPromptLab.render(); document.getElementById('lab-rounds').value = '1'; });
        await page.selectOption('#lab-experiment', 'mock-other');
        assert.equal(await page.locator('#lab-target').inputValue(), 'mock-other', 'simple and advanced target selectors stay synchronized');
        const followStart = requests.length;
        await page.evaluate(() => ByndPromptLab.start());
        assert.equal(await page.evaluate(() => ByndPromptLab.store.read().report.eligible), true);
        assert.ok(requests.slice(followStart).every(body => body.model === 'mock-other'), 'all three independent roles follow a named experiment model');
        assert.ok(requests.slice(followStart).some(body => body.messages[0].content.includes('BYND Prompt 优化器')));
        for (const body of requests.slice(followStart).filter(body => body.messages[0].content.includes('独立评审') || body.messages[0].content.includes('BYND Prompt 优化器'))) assert.equal(body.messages.length, 2, 'judge and optimizer have isolated request contexts');
        await page.evaluate(() => { ByndPromptLab.store.update(data => { data.report = null; }); ByndPromptLab.render(); document.getElementById('lab-rounds').value = '1'; });
        await page.locator('#lab-model-config > summary').click();
        await page.selectOption('#lab-target', 'mock-target');
        assert.equal(await page.locator('#lab-experiment').inputValue(), 'mock-target');
        await page.selectOption('#lab-judge', 'mock-judge');
        await page.selectOption('#lab-proposer', 'mock-proposer');
        const advancedStart = requests.length;
        await page.evaluate(() => ByndPromptLab.start());
        if (!await page.evaluate(() => ByndPromptLab.store.read().report)) throw new Error(await page.locator('#prompt-lab-status').innerText());
        assert.equal(await page.evaluate(() => ByndPromptLab.store.read().report.status), 'complete');
        assert.equal(await page.evaluate(() => ByndPromptLab.store.read().report.eligible), true);
        for (const body of requests.slice(advancedStart)) assert.equal(body.model, body.messages[0]?.content.includes('独立评审') ? 'mock-judge' : body.messages[0]?.content.includes('BYND Prompt 优化器') ? 'mock-proposer' : 'mock-target', 'advanced model overrides route to the correct role');
        assert.ok(requests.some(r => r.temperature === 0.8), 'target uses production sampling');
        assert.ok(requests.some(r => r.temperature === 0), 'judge uses fixed sampling');
        assert.equal(await page.evaluate(() => ByndPromptLab.store.exportData().includes('test-secret')), false);
        assert.ok(await page.evaluate(() => ByndPromptLab.store.read().report.rows.some(row => row.judge?.usage?.[0]?.actualUsage?.total === 110)), 'judge receipt carries actual usage');
        await page.screenshot({ path: path.join(output, 'lab-results-375.png'), animations: 'disabled' });
        await page.reload({ waitUntil: 'domcontentloaded' });
        await page.evaluate(async () => { await byndStylesReady; unlockPhone(); document.documentElement.classList.add('mobile-runtime'); openApp('settings'); ByndBuiltinLibrary?.close(); openSettingsTab('lab'); });
        await page.locator('[data-lab="activate"]').click();
        await page.waitForFunction(() => !!ByndPromptLab.store.read().active);
        assert.match(await page.evaluate(() => ByndPromptLab.prompt()), /保持角色/);
        await page.locator('[data-lab="rollback"]').click();
        assert.equal(await page.evaluate(() => ByndPromptLab.prompt()), '');
        await page.locator('[data-lab="activate"]').click();
        await page.waitForFunction(() => !!ByndPromptLab.store.read().active);
        await page.locator('[data-lab="disable"]').click();
        assert.equal(await page.evaluate(() => ByndPromptLab.prompt()), '');
        for (const failure of ['http', 'judge']) {
            mode = failure;
            await page.evaluate(() => { ByndPromptLab.store.saveDraft(ByndPromptEval.BASELINE); ByndPromptLab.render(); document.getElementById('lab-rounds').value = '1'; });
            await page.evaluate(() => ByndPromptLab.start());
            const report = await page.evaluate(() => ByndPromptLab.store.read().report);
            assert.equal(report.status, 'error'); assert.equal(report.eligible, false);
            assert.ok(report.rows[0].error);
            await page.screenshot({ path: path.join(output, `lab-failure-${failure}-375.png`), animations: 'disabled' });
            await page.evaluate(() => { chatApiRateLimitPauses.clear(); });
        }
        assert.deepEqual(errors, [], 'no browser script errors');
        console.log('Prompt Lab browser checks passed: single default model, built-in policy, independent same-model roles, advanced overrides, 320/375/430px and 47/59px parent/header safe areas, usage receipts, promotion, reload activation, rollback, save/import/export/API/judge failures. Model responses mocked.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
