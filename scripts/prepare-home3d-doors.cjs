'use strict';
// Retain Kenney's authored leaf geometry in a tiny synchronous architecture module.
// No runtime parser, external textures or second Base64 copy is required.
const fs = require('node:fs'), path = require('node:path'), {createHash} = require('node:crypto');
async function main() {
    const tools = path.resolve('artifacts/home3d-tools/node_modules');
    const {NodeIO} = require(path.join(tools, '@gltf-transform/core'));
    const io = new NodeIO(), source = path.resolve(process.argv[2] || 'artifacts/door-kit/source');
    const shapes = {}, assets = [], hash = b => createHash('sha256').update(b).digest('hex');
    for (const [key, name] of [['panel', 'doorway'], ['glazed', 'doorwayFront']]) {
        const file = path.join(source, 'Models/GLTF format', name + '.glb'), bytes = fs.readFileSync(file), doc = await io.read(file);
        const leaf = doc.getRoot().listNodes().find(n => n.getName() === 'door');
        if (!leaf?.getMesh()) throw Error('Missing separately authored door leaf: ' + name);
        shapes[key] = leaf.getMesh().listPrimitives().map(p => ({
            material: p.getMaterial().getName(),
            position: Array.from(p.getAttribute('POSITION').getArray(), v => +v.toFixed(6)),
            normal: Array.from(p.getAttribute('NORMAL').getArray(), v => +v.toFixed(6)),
            index: Array.from(p.getIndices().getArray())
        }));
        assets.push({id: key, sourceFile: name + '.glb', originalSha256: hash(bytes), triangles: shapes[key].reduce((n,p) => n + p.index.length / 3, 0)});
    }
    const output = 'assets/home3d/doors/geometry.js'; fs.mkdirSync(path.dirname(output), {recursive:true});
    const code = '/* Kenney Furniture Kit, CC0; see ../door-manifest.json. Generated by scripts/prepare-home3d-doors.cjs. */\nwindow.ByndHome3D.DoorGeometry=' + JSON.stringify(shapes) + ';\n';
    fs.writeFileSync(output, code);
    fs.copyFileSync(path.join(source, 'License.txt'), 'assets/home3d/licenses/Kenney-Doors-CC0.txt');
    fs.writeFileSync('assets/home3d/door-manifest.json', JSON.stringify({source:'Kenney Furniture Kit',sourceUrl:'https://kenney.nl/assets/furniture-kit',downloadUrl:'https://kenney.nl/media/pages/assets/furniture-kit/440e0608a4-1677580847/kenney_furniture-kit.zip',license:'CC0-1.0',licenseFile:'assets/home3d/licenses/Kenney-Doors-CC0.txt',file:output,sha256:hash(Buffer.from(code)),bytes:Buffer.byteLength(code),processing:'Door leaf only, original indexed geometry and normals; rounded to six decimals. Materials remapped to the selected home palette at runtime. BYND supplies jambs, open passage and frosted sliding variants.',assets},null,2)+'\n');
    console.log('Door geometry:', Buffer.byteLength(code), 'bytes', assets);
}
main().catch(error => { console.error(error); process.exitCode=1; });
