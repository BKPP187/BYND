// Rebuild after updating shipped JPGs. Classic scripts work under file:// too.
const fs = require('node:fs');
const path = require('node:path');
const dir = path.resolve(__dirname, '../assets/characters/builtin');
const assets = Object.fromEntries(fs.readdirSync(dir).filter(name => name.endsWith('.jpg')).sort().map(name => [
    'assets/characters/builtin/' + name,
    'data:image/jpeg;base64,' + fs.readFileSync(path.join(dir, name)).toString('base64')
]));
fs.writeFileSync(path.join(dir, 'artwork.js'), '// Generated by scripts/bundle-character-art.cjs; do not edit.\nwindow.ByndBuiltinArtwork = ' + JSON.stringify(assets) + ';\n');
